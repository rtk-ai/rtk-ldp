/**
 * build-search-index.mjs
 *
 * Parses all RTK docs .md files → extracts H2 headings → generates search entries.
 * Output: src/data/docs-search-entries.ts (gitignored, generated at build time)
 *
 * Run: node scripts/build-search-index.mjs
 */

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from 'fs'
import { resolve, dirname, relative, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const CONTENT_DIR = resolve(ROOT, 'src/content/docs/guide')
const OUT_PATH = resolve(ROOT, 'src/data/docs-search-entries.ts')

const SKIP_HEADINGS = new Set([
  'table of contents', 'toc', 'contents', 'overview',
])

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, ' ')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function getPageUrl(relPath) {
  const withoutExt = relPath.replace(/\.md$/, '')
  const normalized = withoutExt.replace(/\\/g, '/')
  const slug = normalized === 'index' ? '' : normalized.replace(/\/index$/, '')
  return `/guide/${slug}/`
}

function extractFrontmatterTitle(content) {
  const match = content.match(/^---\s*\n([\s\S]*?)\n---/)
  if (!match) return ''
  const fm = match[1]
  const titleMatch = fm.match(/^title:\s*["']?(.+?)["']?\s*$/m)
  return titleMatch ? titleMatch[1].trim() : ''
}

function stripMarkdown(text) {
  return text
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`[^`]+`/g, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/!\[.*?\]\(.*?\)/g, ' ')
    .replace(/^#{1,6}\s+/gm, ' ')
    .replace(/[|*_>#~]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function extractH2Sections(content) {
  const lines = content.split('\n')
  const fileTitle = extractFrontmatterTitle(content)
  const sections = []

  let inFrontmatter = false
  let frontmatterDone = false
  let fmLineCount = 0
  let currentHeading = null
  let currentLines = []

  for (const line of lines) {
    if (!frontmatterDone) {
      if (line.trim() === '---') {
        fmLineCount++
        inFrontmatter = fmLineCount === 1
        if (fmLineCount === 2) frontmatterDone = true
        continue
      }
      if (inFrontmatter) continue
    }

    const h2Match = line.match(/^## (.+)$/)
    if (h2Match) {
      if (currentHeading !== null) {
        sections.push({ heading: currentHeading, contentExcerpt: currentLines.join('\n'), fileTitle })
      }
      currentHeading = h2Match[1].trim()
      currentLines = []
      continue
    }

    if (currentHeading !== null && currentLines.length < 30) {
      currentLines.push(line)
    }
  }

  if (currentHeading !== null) {
    sections.push({ heading: currentHeading, contentExcerpt: currentLines.join('\n'), fileTitle })
  }

  return sections
}

function buildKeywords(heading, fileTitle, contentExcerpt) {
  const headingWords = heading.replace(/[^\p{L}\p{N}\s]/gu, ' ').toLowerCase()
  const titleWords = fileTitle.replace(/[^\p{L}\p{N}\s]/gu, ' ').toLowerCase()
  const excerpt = stripMarkdown(contentExcerpt).slice(0, 150).toLowerCase()
  return `${headingWords} ${titleWords} ${excerpt}`.replace(/\s+/g, ' ').trim().slice(0, 200)
}

function makeId(relPath, heading) {
  const fileSlug = relPath.replace(/\.md$/, '').replace(/[/\\]/g, '-')
  const headingSlug = slugify(heading).slice(0, 50)
  return `rtk-${fileSlug}-${headingSlug}`.replace(/-+/g, '-').replace(/^-|-$/g, '')
}

function listMdFiles(dir, baseDir = dir) {
  if (!existsSync(dir)) return []
  const results = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      results.push(...listMdFiles(full, baseDir))
    } else if (entry.endsWith('.md')) {
      results.push(relative(baseDir, full))
    }
  }
  return results
}

function generateTS(entries) {
  const json = JSON.stringify(entries, null, 2)
  return `// Auto-generated by scripts/build-search-index.mjs
// Do not edit directly — run: pnpm build:search
// Generated: ${new Date().toISOString().slice(0, 10)}

export interface DocsSearchEntry {
  id: string
  title: string
  keywords: string
  category: string
  url: string
  source: 'docs'
}

export const DOCS_SEARCH_ENTRIES: DocsSearchEntry[] = ${json}
`
}

function main() {
  // Ensure output directory exists
  mkdirSync(resolve(ROOT, 'src/data'), { recursive: true })

  if (!existsSync(CONTENT_DIR)) {
    console.warn(`[build-search-index] WARNING: Content dir not found: ${CONTENT_DIR}`)
    console.warn('[build-search-index] Run prepare-docs.mjs first, or set RTK_REPO_PATH.')
    writeFileSync(OUT_PATH, generateTS([]), 'utf-8')
    return
  }

  const files = listMdFiles(CONTENT_DIR)
  const entries = []
  let fileCount = 0

  for (const relPath of files) {
    const fullPath = join(CONTENT_DIR, relPath)
    const content = readFileSync(fullPath, 'utf-8')
    const sections = extractH2Sections(content)
    const pageUrl = getPageUrl(relPath)
    const fileTitle = extractFrontmatterTitle(content)

    for (const { heading, contentExcerpt } of sections) {
      const headingLower = heading.trim().toLowerCase().replace(/^[^\p{L}]+/u, '').trim()
      if (SKIP_HEADINGS.has(headingLower)) continue

      entries.push({
        id: makeId(relPath, heading),
        title: heading,
        keywords: buildKeywords(heading, fileTitle, contentExcerpt),
        category: 'RTK Docs',
        url: pageUrl + '#' + slugify(heading),
        source: 'docs',
      })
    }

    fileCount++
  }

  console.log(`[build-search-index] Parsed ${fileCount} files → ${entries.length} entries`)
  writeFileSync(OUT_PATH, generateTS(entries), 'utf-8')
  console.log(`[build-search-index] Written to ${OUT_PATH}`)
}

main()
